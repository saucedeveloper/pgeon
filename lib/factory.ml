let cardinal factory = FactoryTermSet.cardinal factory.set

(* Factory to string *)
let string_of_factory factory =
  if (cardinal factory) = 0 then
    "{}"
  else
    let node_list = FactoryTermSet.to_list factory.set in
    let node_string_list = List.map string_of_node node_list in
    "{ " ^ (String.concat ", " node_string_list) ^ " }"

(* String of a term with strings of
recursive elements given by `custom_string_of` *)
let string_of_node_custom node custom_string_of =
  let string_of node = match node with
      | Bvar i -> Printf.sprintf "#%d" i
      | Fvar x -> "'" ^ x
      | Mvar x -> "?" ^ x
      | App (f, []) -> f
      | App (f, args) ->
          Printf.sprintf "%s(%s)" f
            (String.concat ", " (List.map custom_string_of (term_list_deref args)))
      | Bind (b, body) -> Printf.sprintf "%s.(%s)" b (custom_string_of (term_deref body))
    in
    string_of node

(* String of factory where each element of depth > 0
is written as its address in factory *)
let debug_string_of_factory factory =
  if (FactoryTermSet.cardinal factory.set) = 0 then
    "{}"
  else
    let rec recursive depth node =
      if depth = 0 then
        let compact_string =
          string_of_node_custom node (recursive (depth + 1))
        in
        compact_string ^ "(@" ^ (string_address_of node) ^ ")"
      else
        let string_of_node =
          if (FactoryTermSet.mem node factory.set) then
            "{@" ^ (string_address_of node) ^ "}"
          else
            "{@?" ^ (string_address_of node) ^ "}"
        in
          string_of_node
      in

    let node_list = FactoryTermSet.to_list factory.set in
    let node_string_list = List.map (recursive 0) node_list in
    "{ " ^ (String.concat ", " node_string_list) ^ " }"

