type name = string

(* Term with references *)
type node =
  | Bvar of int (* de Bruijn index *)
  | Fvar of name (* free variable, generated by rules *)
  | Mvar of name
    (* meta variable, used in rule definition. Cannot appear in the tableau *)
  | App of name * node ref list
  | Bind of name * node ref

(* Type exposed publicly *)
type term = node ref

(* Dereference term ref *)
let term_deref t = !t

(* Public name of term_deref *)
let term_match = term_deref

(* List of term ref to list or term *)
let term_list_deref l = List.map term_deref l

let is_bvar term = (
  match !term with
  | Bvar index -> Some index
  | _ -> None
)
let is_fvar term = (
  match !term with
  | Fvar name -> Some name
  | _ -> None
)
let is_mvar term = (
  match !term with
  | Mvar name -> Some name
  | _ -> None
)
let is_app term = (
  match !term with
  | App (name, terms) -> Some (name, terms)
  | _ -> None
)
let is_bind term = (
  match !term with
  | Bind (name, term) -> Some (name, term)
  | _ -> None
)

let node_bvar_compare a_index b_index = compare a_index b_index

let node_fvar_compare a_name b_name = compare a_name b_name

let node_mvar_compare a_name b_name = compare a_name b_name

(* Compare App variants for Set implementation *)
let rec node_app_compare a_name a_terms b_name b_terms =
  let name_comparison = compare a_name b_name in
  if name_comparison <> 0 then
    name_comparison
  else
    let arity_comparison = compare (List.length a_terms) (List.length b_terms) in
    if arity_comparison <> 0 then
      arity_comparison
    else
      let () = assert ((List.length a_terms) = (List.length b_terms)) in
      let combined_terms = List.combine a_terms b_terms in
      let term_tuple_compare tup = match tup with (a, b) -> term_compare a b in
      let term_comparisons = List.map term_tuple_compare combined_terms in
      let non_zero_comparison c = c <> 0 in
      let first_non_zero_comparison = List.find_opt non_zero_comparison term_comparisons in
      Option.value first_non_zero_comparison ~default:0

(* Compare Bind variants for Set implementation *)
and node_bind_compare a_name a_term b_name b_term =
  let name_comparison = compare a_name b_name in
      if name_comparison <> 0 then
        name_comparison
      else
        term_compare a_term b_term

(* Compare terms for Set implementation *)
and term_compare a b =
  if a = b then
    0
  else
    node_compare !a !b

(* Compare terms by variant index then by contents recursively *)
and node_compare a b =
  match (a, b) with
  | (Bvar a_bvar, Bvar b_bvar) -> node_bvar_compare a_bvar b_bvar
  | (Bvar _, _) -> -1
  | (_, Bvar _) -> 1
  | (Fvar a_fvar, Fvar b_fvar) -> node_fvar_compare a_fvar b_fvar
  | (Fvar _, _) -> -1
  | (_, Fvar _) -> 1
  | (Mvar a_mvar, Mvar b_mvar) -> node_mvar_compare a_mvar b_mvar
  | (Mvar _, _) -> -1
  | (_, Mvar _) -> 1
  | (App (a_app_name, a_app_terms), App (b_app_name, b_app_terms)) ->
      node_app_compare a_app_name a_app_terms b_app_name b_app_terms
  | (App _, _) -> -1
  | (_, App _) -> 1
  | (Bind (a_bind_name, a_bind_term), Bind (b_bind_name, b_bind_term)) ->
      node_bind_compare a_bind_name a_bind_term b_bind_name b_bind_term

let term_equal a b = (a = b)

(* Module for Set implementation *)
module FactoryTerm = struct
  type t = node
  let compare = node_compare
end

module FactoryTermSet = Set.Make(FactoryTerm)

(* Factory is a set of terms using node_compare to tell them apart *)
type t = {
  set : FactoryTermSet.t;
}

(* Empty factory *)
let empty = {
  set = FactoryTermSet.empty
}

(* term to string implementation from compile.ml *)
let string_of_node node =
  let rec string_of_node = function
      | Bvar i -> Printf.sprintf "#%d" i
      | Fvar x -> "'" ^ x
      | Mvar x -> "?" ^ x
      | App (f, []) -> f
      | App (f, args) ->
          Printf.sprintf "%s(%s)" f
            (String.concat ", " (List.map string_of_node (term_list_deref args)))
      | Bind (b, body) -> Printf.sprintf "%s.(%s)" b (string_of_node (term_deref body))
    in
    string_of_node node

let string_of_term term = string_of_node !term

(* Address / unique id for x for printing *)
let address_of x = 2 * (Obj.magic x) / 2

let string_address_of x =
  let s = string_of_int (address_of x) in
  let i = 4 in
  String.sub s (String.length s - i) i

(* Create or get Bvar in factory *)
let create_bvar index factory =
  let target = Bvar index in
  let existing_search = FactoryTermSet.find_opt target factory.set in (
  match existing_search with
  | Some existing ->
    (* Printf.printf "create_bvar(%d).existing: targ %s, exst %s\n" index (string_address_of target) (string_address_of existing); *)
    (ref existing, factory)
  | None ->
    (* Printf.printf "create_bvar(%d).created: targ %s\n" index (string_address_of target); *)
    let new_factory = { set = (FactoryTermSet.add target factory.set) } in
    (ref target, new_factory)
  )

