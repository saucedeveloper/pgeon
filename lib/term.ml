type name = int

type t =
  | Bvar of int (* de Bruijn index *)
  | Fvar of name (* free variable, generated by rules *)
  | Mvar of name
    (* meta variable, used in rule definition. Cannot appear in the tableau *)
  | App of name * t list
  | Bind of name * t

let equal (a : t) b = a = b

let rec occurs n = function
  | Bvar _ | Fvar _ -> false
  | Mvar n' -> n = n'
  | App (_, p) -> List.exists (occurs n) p
  | Bind (_, t) -> occurs n t

let var_open u t =
  let rec var_open k u = function
    | Bvar i as t -> if i = k then u else t
    | (Fvar _ | Mvar _) as t -> t
    | App (name, tl) -> App (name, List.map (var_open k u) tl)
    | Bind (name, t) -> Bind (name, var_open (k + 1) u t)
  in
  snd (List.fold_left (fun (i, t) u -> (i + 1, var_open i u t)) (0, t) u)

let rec substitute subs = function
  | (Bvar _ | Fvar _) as t -> t
  | Mvar x -> ( match List.assoc_opt x subs with None -> Mvar x | Some u -> u)
  | App (name, tl) -> App (name, List.map (substitute subs) tl)
  | Bind (name, t) -> Bind (name, substitute subs t)

let rule_match t t' =
  let exception UnifyFailure in
  let rec rule_match dt = function
    | [], [] -> dt
    | Bvar i :: tl, Bvar j :: tl' ->
        if i = j then rule_match dt (tl, tl') else raise UnifyFailure
    | Bvar _ :: _, _ | _, Bvar _ :: _ -> raise UnifyFailure
    | _, Fvar _ :: _ ->
        Log.error "unexpected free variable in rule\n";
        raise UnifyFailure
    | Mvar _ :: _, _ ->
        Log.error "unexpected meta variable in tableau\n";
        raise UnifyFailure
    | App (f, p) :: tl, App (f', p') :: tl'
      when f = f' && List.length p = List.length p' ->
        rule_match dt (p @ tl, p' @ tl')
    | Bind (b, t) :: tl, Bind (b', t') :: tl' when b = b' ->
        rule_match dt (t :: tl, t' :: tl')
    | t :: tl, Mvar n :: tl' ->
        if occurs n t then raise UnifyFailure
        else
          let dt = List.map (fun (m, t') -> (m, substitute [ (n, t) ] t')) dt
          and tl' = List.map (substitute [ (n, t) ]) tl' in
          rule_match ((n, t) :: dt) (tl, tl')
    | _ -> raise UnifyFailure
  in
  try Some (rule_match [] (t, t')) with UnifyFailure -> None
